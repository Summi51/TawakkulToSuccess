// Explain the concept of the Virtual DOM in React?

// Virtual DOM is a lightweight copy of the real DOM. React 
// compares the old and new Virtual DOM and updates only the changed parts in the real DOM.

// 🧠 Remember:
// Virtual DOM → Compare → Update only changed parts

